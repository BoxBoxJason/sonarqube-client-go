const (
	// updateDocsEnv, when set, makes TestServicesReference rewrite the generated page instead of comparing it.
	updateDocsEnv = "UPDATE_DOCS"

	docsContentDir = "../../docs/content/docs"
	servicesFile   = "services.md"
	cliFile        = "cli.md"
	sdkFile        = "sdk.md"

	pkgDocURL = "https://pkg.go.dev/github.com/boxboxjason/sonarqube-client-go/v2/sonar"

	docsFilePermission = 0o600
)

var (
	// cliEnvVarPattern finds the environment variables read by the CLI global flags.
	cliEnvVarPattern = regexp.MustCompile(`os\.Getenv\("(SONAR_CLI_[A-Z_]+)"\)`)
	// sdkEnvVarPattern finds the environment variables read by sonar.NewClientFromEnv.
	sdkEnvVarPattern = regexp.MustCompile(`Env[A-Za-z]+\s*=\s*"(SONAR_[A-Z_]+)"`)
	// cliExampleBlockPattern finds the shell code blocks of a documentation page.
	cliExampleBlockPattern = regexp.MustCompile("(?s)```bash\n(.*?)```")
	// cliFlagPattern finds the flags of a command line.
	cliFlagPattern = regexp.MustCompile(`(?:^|\s)--([a-z][a-z0-9-]*)`)
)

// newDocumentedRootCmd builds the complete command tree the way the documentation
// describes it: without any inherited environment.
func newDocumentedRootCmd(t *testing.T) *cobra.Command {
	t.Helper()

	for _, name := range envVarsIn(t, "root.go", cliEnvVarPattern) {
		t.Setenv(name, "")
	}

	flags := &globalFlags{output: defaultOutputFormat} //nolint:exhaustruct // set by flag binding
	rootCmd := buildRootCommand(flags)
	RegisterAllCommands(rootCmd, &flags.output)
	// Cobra adds the completion command when the CLI runs.
	rootCmd.InitDefaultCompletionCmd()

	return rootCmd
}

func envVarsIn(t *testing.T, path string, pattern *regexp.Regexp) []string {
	t.Helper()

	source, err := os.ReadFile(path)
	if err != nil {
		t.Fatalf("reading %s: %v", path, err)
	}

	var names []string
	for _, match := range pattern.FindAllStringSubmatch(string(source), -1) {
		names = append(names, match[1])
	}

	if len(names) == 0 {
		t.Fatalf("found no environment variable in %s, the pattern is out of date", path)
	}

	return names
}

func readDocsPage(t *testing.T, name string) string {
	t.Helper()

	content, err := os.ReadFile(filepath.Join(docsContentDir, name))
	if err != nil {
		t.Fatalf("reading the %s documentation page: %v", name, err)
	}

	return string(content)
}

func findSubcommand(parent *cobra.Command, name string) *cobra.Command {
	for _, command := range parent.Commands() {
		if command.Name() == name {
			return command
		}
	}

	return nil
}

// renderServicesReference renders the services of the SDK and their CLI commands as a documentation page.
func renderServicesReference(rootCmd *cobra.Command) string {
	var page strings.Builder

	page.WriteString("---\ntitle: Services\nweight: 70\n---\n\n")
	page.WriteString("<!-- Code generated by TestServicesReference (run `make docs-generate`); DO NOT EDIT. -->\n\n")
	page.WriteString("{{< callout type=\"info\" >}}\nThis page is generated from the SDK and the CLI, so it always matches the code. ")
	page.WriteString("The parameters and the responses of every method are in the [API reference](" + pkgDocURL + ").\n{{< /callout >}}\n")

	page.WriteString("\n## V1 API services\n\n")
	page.WriteString("Each service is a field of the client, and a command of `sonar-cli` whose subcommands are its methods.\n\n")

	for field := range reflect.TypeFor[sonar.Client]().Fields() {
		if !field.IsExported() || field.Type.Kind() != reflect.Pointer || field.Type.Elem().Kind() != reflect.Struct {
			continue
		}

		serviceCmd := findSubcommand(rootCmd, pascalToKebab(field.Name))
		if serviceCmd == nil {
			continue
		}

		methods := make([]string, 0, len(serviceCmd.Commands()))
		for _, methodCmd := range serviceCmd.Commands() {
			methods = append(methods, "`"+methodCmd.Name()+"`")
		}

		// Only the curated descriptions: the generic fallback adds nothing to the table.
		description := serviceDescriptions[field.Name]

		if description != "" {
			description = ": " + description
		}

		page.WriteString("- **`" + serviceCmd.Name() + "`** ([`client." + field.Name + "`](" + pkgDocURL + "#" + field.Type.Elem().Name() + "))" +
			description + "  \n  " + strings.Join(methods, ", ") + "\n")
	}

	page.WriteString("\n## V2 API services\n\n")
	page.WriteString("The V2 services are grouped under `client.V2`. They are available in the Go SDK only.\n\n")
	page.WriteString("| Go SDK | Type |\n| ------ | ---- |\n")

	for field := range reflect.TypeFor[sonar.ServicesV2]().Fields() {
		if !field.IsExported() || field.Type.Kind() != reflect.Pointer {
			continue
		}

		typeName := field.Type.Elem().Name()
		page.WriteString("| `client.V2." + field.Name + "` | [`" + typeName + "`](" + pkgDocURL + "#" + typeName + ") |\n")
	}

	page.WriteString("\n## CLI global flags\n\n```text\n" + strings.TrimSpace(rootCmd.PersistentFlags().FlagUsages()) + "\n```\n")

	return page.String()
}

// TestServicesReference fails when the generated services page no longer matches the SDK and the CLI.
// Regenerate it with `make docs-generate`.
func TestServicesReference(t *testing.T) {
	want := renderServicesReference(newDocumentedRootCmd(t))
	path := filepath.Join(docsContentDir, servicesFile)

	if os.Getenv(updateDocsEnv) != "" {
		if err := os.WriteFile(path, []byte(want), docsFilePermission); err != nil {
			t.Fatalf("writing %s: %v", path, err)
		}

		return
	}

	got, err := os.ReadFile(path)
	if err != nil {
		t.Fatalf("reading %s: %v (run `make docs-generate`)", path, err)
	}

	if string(got) != want {
		t.Fatalf("%s is out of date, run `make docs-generate` and commit the result", path)
	}
}

// TestDocsCoverGlobalFlags fails when a global flag or its environment variable is not documented in the CLI page.
func TestDocsCoverGlobalFlags(t *testing.T) {
	page := readDocsPage(t, cliFile)

	newDocumentedRootCmd(t).PersistentFlags().VisitAll(func(flag *pflag.Flag) {
		if !strings.Contains(page, "`--"+flag.Name+"`") {
			t.Errorf("global flag --%s is not documented in docs/content/docs/%s", flag.Name, cliFile)
		}
	})

	for _, name := range envVarsIn(t, "root.go", cliEnvVarPattern) {
		if !strings.Contains(page, "`"+name+"`") {
			t.Errorf("environment variable %s is not documented in docs/content/docs/%s", name, cliFile)
		}
	}
}

// TestDocsCoverSDKEnvVars fails when an environment variable read by NewClientFromEnv is not documented.
func TestDocsCoverSDKEnvVars(t *testing.T) {
	page := readDocsPage(t, sdkFile)

	for _, name := range envVarsIn(t, "../../sonar/env.go", sdkEnvVarPattern) {
		if !strings.Contains(page, "`"+name+"`") {
			t.Errorf("environment variable %s is not documented in docs/content/docs/%s", name, sdkFile)
		}
	}
}

// TestDocsCLIExamples fails when a sonar-cli example of the documentation or of the README
// uses a service, a method or a flag that does not exist.
func TestDocsCLIExamples(t *testing.T) {
	rootCmd := newDocumentedRootCmd(t)
	pages := map[string]string{"README.md": "../../README.md"}

	entries, err := os.ReadDir(docsContentDir)
	if err != nil {
		t.Fatalf("listing %s: %v", docsContentDir, err)
	}

	for _, entry := range entries {
		pages[entry.Name()] = filepath.Join(docsContentDir, entry.Name())
	}

	checked := 0

	for name, path := range pages {
		content, err := os.ReadFile(path)
		if err != nil {
			t.Fatalf("reading %s: %v", path, err)
		}

		for _, block := range cliExampleBlockPattern.FindAllStringSubmatch(string(content), -1) {
			for line := range strings.SplitSeq(block[1], "\n") {
				line = strings.TrimSpace(line)
				if !strings.HasPrefix(line, "sonar-cli ") {
					continue
				}

				checked++

				checkCLIExample(t, rootCmd, name, line)
			}
		}
	}

	if checked == 0 {
		t.Fatal("found no sonar-cli example, the pattern is out of date")
	}
}

func checkCLIExample(t *testing.T, rootCmd *cobra.Command, page, line string) {
	t.Helper()

	// Keep the command itself: drop pipes, redirections and comments.
	command, _, _ := strings.Cut(line, "|")
	command, _, _ = strings.Cut(command, ">")
	command, _, _ = strings.Cut(command, "#")

	// The positional words (service and method) are the words that are neither flags nor flag values.
	var words []string

	fields := strings.Fields(command)[1:]
	for index := 0; index < len(fields); index++ {
		field := fields[index]
		if strings.HasPrefix(field, "-") {
			if flag := lookupFlag(rootCmd, words, strings.TrimLeft(field, "-")); flag != nil && flag.Value.Type() != "bool" && !strings.Contains(field, "=") {
				index++ // skip the flag value
			}

			continue
		}

		words = append(words, field)
	}

	target := rootCmd
	for _, word := range words {
		next := findSubcommand(target, word)
		if next == nil {
			// Past the method, the remaining words are arguments (for example the value of an unknown flag).
			if target == rootCmd || target.HasSubCommands() {
				t.Errorf("%s: %q: unknown command %q", page, line, word)
			}

			break
		}

		target = next
	}

	for _, match := range cliFlagPattern.FindAllStringSubmatch(command, -1) {
		name := match[1]
		if name == "help" || name == "version" {
			continue
		}

		if target.Flags().Lookup(name) == nil && target.InheritedFlags().Lookup(name) == nil && rootCmd.PersistentFlags().Lookup(name) == nil {
			t.Errorf("%s: %q: unknown flag --%s for %q", page, line, name, target.CommandPath())
		}
	}
}

// lookupFlag finds a flag on the command designated by the positional words read so far.
func lookupFlag(rootCmd *cobra.Command, words []string, name string) *pflag.Flag {
	name, _, _ = strings.Cut(name, "=")

	target := rootCmd
	for _, word := range words {
		if next := findSubcommand(target, word); next != nil {
			target = next
		}
	}

	if flag := target.Flags().Lookup(name); flag != nil {
		return flag
	}

	return rootCmd.PersistentFlags().Lookup(name)
}
